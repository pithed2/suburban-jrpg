def grid_image(art: str) -> Image.Image:
    rows = [row for row in art.strip("\n").split("\n")]
    width = max(len(row) for row in rows)
    img = Image.new("RGBA", (width, len(rows)), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != "." and ch in PALETTE:
                img.putpixel((x, y), PALETTE[ch] + (255,))
    return img


def tile(base, specks=(), seed=0, density=0.18):
    rng = random.Random(seed)
    img = Image.new("RGBA", (16, 16), base + (255,))
    for y in range(16):
        for x in range(16):
            if specks and rng.random() < density:
                img.putpixel((x, y), rng.choice(specks) + (255,))
    return img


def overlay(base: Image.Image, art: str) -> Image.Image:
    out = base.copy()
    out.alpha_composite(grid_image(art))
    return out


def lines(img: Image.Image, color, every=4, vertical=False) -> Image.Image:
    out = img.copy()
    for i in range(0, 16, every):
        for j in range(16):
            out.putpixel((i, j) if vertical else (j, i), color + (255,))
    return out


